V_DESIGN=50.0
def thru_note(pts):
    p0,p1,p2,p3=[np.array(p,float) for p in pts]
    d=(p1-p0)/np.linalg.norm(p1-p0); n=np.array([-d[1],d[0]])
    off=abs(np.dot(p3-p0,n))/K; L=np.linalg.norm(p2-p1)/K
    req=off*V_DESIGN**2/155
    return off,L,req

